// Package dhcp — раздача адресов в LAN через dnsmasq отдельной службой:
// демон пишет ей конфиг и закреплённые адреса устройств и читает аренды.
// dnsmasq не зависит от демона: упал демон — адреса выдаются дальше.
package dhcp

import (
	"bufio"
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"net/netip"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"sync"
	"syscall"
	"time"

	"tross/core/model"
)

// Config — раздача адресов.
type Config struct {
	Interface   string
	Prefix      netip.Prefix // сеть LAN, в которой диапазон
	First, Last netip.Addr
	Gateway     netip.Addr // шлюз и DNS для устройств
	Lease       time.Duration
	Dir         string
	PIDFile     string
	// Unit — служба systemd с dnsmasq; пусто — службы нет.
	Unit string
}

func (c Config) confPath() string   { return filepath.Join(c.Dir, "dnsmasq.conf") }
func (c Config) hostsPath() string  { return filepath.Join(c.Dir, "hosts") }
func (c Config) leasesPath() string { return filepath.Join(c.Dir, "leases") }

func mask(p netip.Prefix) string {
	m := ^uint32(0) << (32 - p.Bits())
	return netip.AddrFrom4([4]byte{byte(m >> 24), byte(m >> 16), byte(m >> 8), byte(m)}).String()
}

// RenderConf — основной конфиг dnsmasq. DNS у этого экземпляра выключен
// (port=0): DNS дома — резолвер демона и запасной резолвер.
func RenderConf(c Config) (string, error) {
	for _, s := range []string{c.Interface, c.Dir, c.PIDFile} {
		if s == "" || strings.ContainsAny(s, "\n\r") {
			return "", fmt.Errorf("dhcp: bad value %q", s)
		}
	}
	if !c.Prefix.Contains(c.First) || !c.Prefix.Contains(c.Last) || !c.Prefix.Contains(c.Gateway) {
		return "", fmt.Errorf("dhcp: range %s-%s or gateway %s outside %s", c.First, c.Last, c.Gateway, c.Prefix)
	}
	var b strings.Builder
	b.WriteString("# Generated by trossd: edits are overwritten.\n")
	b.WriteString("port=0\n")
	fmt.Fprintf(&b, "interface=%s\nbind-interfaces\n", c.Interface)
	fmt.Fprintf(&b, "dhcp-range=%s,%s,%s,%d\n", c.First, c.Last, mask(c.Prefix), int(c.Lease/time.Second))
	fmt.Fprintf(&b, "dhcp-option=option:router,%s\n", c.Gateway)
	fmt.Fprintf(&b, "dhcp-option=option:dns-server,%s\n", c.Gateway)
	// Единственный сервер в сети: отвечает и на продление чужих аренд —
	// после замены роутерной раздачи устройства не ждут истечения.
	b.WriteString("dhcp-authoritative\n")
	fmt.Fprintf(&b, "dhcp-leasefile=%s\n", c.leasesPath())
	fmt.Fprintf(&b, "dhcp-hostsfile=%s\n", c.hostsPath())
	fmt.Fprintf(&b, "pid-file=%s\n", c.PIDFile)
	return b.String(), nil
}

// Reservation — закреплённый адрес: у объединённой записи — все её MAC
// (одновременно адрес держит только один из них).
type Reservation struct {
	MACs []model.MAC
	Addr netip.Addr
}

// RenderHosts — файл закреплённых адресов (dhcp-hostsfile), по адресу.
func RenderHosts(rs []Reservation) string {
	rs = slices.Clone(rs)
	slices.SortFunc(rs, func(a, b Reservation) int { return a.Addr.Compare(b.Addr) })
	var b strings.Builder
	for _, r := range rs {
		if len(r.MACs) == 0 || !r.Addr.Is4() {
			continue
		}
		for _, m := range r.MACs {
			b.WriteString(m.String())
			b.WriteByte(',')
		}
		b.WriteString(r.Addr.String())
		b.WriteByte('\n')
	}
	return b.String()
}

// Lease — аренда из файла dnsmasq.
type Lease struct {
	Expires  time.Time  `json:"expires"`
	MAC      model.MAC  `json:"mac"`
	Addr     netip.Addr `json:"addr"`
	Hostname string     `json:"hostname,omitempty"`
}

// ParseLeases — строки «срок MAC адрес имя client-id»; непонятные строки
// пропускаются.
func ParseLeases(r io.Reader) []Lease {
	var out []Lease
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) < 4 {
			continue
		}
		exp, err1 := strconv.ParseInt(f[0], 10, 64)
		mac, err2 := model.ParseMAC(f[1])
		ip, err3 := netip.ParseAddr(f[2])
		if err1 != nil || err2 != nil || err3 != nil || !ip.Is4() {
			continue
		}
		l := Lease{Expires: time.Unix(exp, 0), MAC: mac, Addr: ip}
		if f[3] != "*" {
			l.Hostname = f[3]
		}
		out = append(out, l)
	}
	return out
}

// Manager — файлы dnsmasq и сигналы ему.
type Manager struct {
	cfg Config
	log *slog.Logger
	// systemctl — запуск команды (подменяется в тестах).
	systemctl func(ctx context.Context, args ...string) error

	mu    sync.Mutex
	hosts string
}

func NewManager(cfg Config, log *slog.Logger) *Manager {
	return &Manager{cfg: cfg, log: log, systemctl: func(ctx context.Context, args ...string) error {
		out, err := exec.CommandContext(ctx, "systemctl", args...).CombinedOutput()
		if err != nil {
			return fmt.Errorf("systemctl %s: %w: %s", strings.Join(args, " "), err, bytes.TrimSpace(out))
		}
		return nil
	}}
}

// writeIfChanged — атомарная замена файла; false — содержимое то же.
func writeIfChanged(path, content string) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && string(old) == content {
		return false, nil
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return false, err
	}
	return true, os.Rename(tmp, path)
}

// Start пишет конфиг и при его смене (или если dnsmasq не запущен)
// перезапускает службу. Без службы — только предупреждение.
func (m *Manager) Start(ctx context.Context, rs []Reservation) error {
	conf, err := RenderConf(m.cfg)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(m.cfg.Dir, 0o755); err != nil {
		return err
	}
	m.mu.Lock()
	m.hosts = RenderHosts(rs)
	hosts := m.hosts
	m.mu.Unlock()
	if _, err := writeIfChanged(m.cfg.hostsPath(), hosts); err != nil {
		return err
	}
	changed, err := writeIfChanged(m.cfg.confPath(), conf)
	if err != nil {
		return err
	}
	if !changed && m.Running() {
		return m.reload()
	}
	if m.cfg.Unit == "" {
		if changed && m.Running() {
			m.log.Warn("dhcp: dnsmasq config changed: restart dnsmasq", "conf", m.cfg.confPath())
		}
		return nil
	}
	m.log.Info("dhcp: (re)starting the DHCP service", "unit", m.cfg.Unit, "config_changed", changed)
	return m.systemctl(ctx, "restart", m.cfg.Unit)
}

// SetReservations переписывает закреплённые адреса и просит dnsmasq их
// перечитать (SIGHUP), если что-то изменилось.
func (m *Manager) SetReservations(rs []Reservation) error {
	h := RenderHosts(rs)
	m.mu.Lock()
	same := h == m.hosts
	m.hosts = h
	m.mu.Unlock()
	if same {
		return nil
	}
	if _, err := writeIfChanged(m.cfg.hostsPath(), h); err != nil {
		return err
	}
	return m.reload()
}

func (m *Manager) pid() (int, bool) {
	b, err := os.ReadFile(m.cfg.PIDFile)
	if err != nil {
		return 0, false
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(b)))
	return pid, err == nil && pid > 1
}

// Running — процесс из pid-файла жив.
func (m *Manager) Running() bool {
	pid, ok := m.pid()
	if !ok {
		return false
	}
	p, err := os.FindProcess(pid)
	return err == nil && p.Signal(syscall.Signal(0)) == nil
}

var errNotRunning = errors.New("dhcp: dnsmasq is not running")

func (m *Manager) reload() error {
	pid, ok := m.pid()
	if !ok {
		return errNotRunning
	}
	p, err := os.FindProcess(pid)
	if err != nil {
		return err
	}
	return p.Signal(syscall.SIGHUP)
}

// Leases — текущие аренды (файл dnsmasq).
func (m *Manager) Leases() ([]Lease, error) {
	f, err := os.Open(m.cfg.leasesPath())
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return ParseLeases(f), nil
}

func (m *Manager) Config() Config { return m.cfg }
